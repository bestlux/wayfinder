export function buildCharacterWealthPolicy(fixture) {
  const extracted = extractPinnedCharacterWealthFixture(fixture);
  const dataDigest = digest(characterWealthDataSha256(extracted.rows));
  const artifactPayload = {
    schemaVersion: CHARACTER_WEALTH_SCHEMA_VERSION,
    policyId: CHARACTER_WEALTH_POLICY_ID,
    policyVersion: CHARACTER_WEALTH_POLICY_VERSION,
    dataDigest,
    source: {
      pf2eVersion: PINNED_CHARACTER_WEALTH_SOURCE.pf2eVersion,
      commit: PINNED_CHARACTER_WEALTH_SOURCE.pf2eCommit,
      path: PINNED_CHARACTER_WEALTH_SOURCE.upstreamPath,
      journalId: PINNED_CHARACTER_WEALTH_SOURCE.journalId,
      pageId: PINNED_CHARACTER_WEALTH_SOURCE.pageId,
      fixtureDigest: digest(sha256(canonicalJson(fixture))),
      sourceDigest: PINNED_CHARACTER_WEALTH_SOURCE.sourceDigest,
      tableDigest: PINNED_CHARACTER_WEALTH_SOURCE.tableDigest,
    },
    tableIdentity: {
      heading: CHARACTER_WEALTH_TABLE_IDENTITY.heading,
      classTokens: [...CHARACTER_WEALTH_TABLE_IDENTITY.classTokens],
      headers: [...CHARACTER_WEALTH_TABLE_IDENTITY.headers],
      attribution: {
        journalFooter: CHARACTER_WEALTH_TABLE_IDENTITY.attribution,
        book: CHARACTER_WEALTH_TABLE_IDENTITY.book,
        journalPages: [...CHARACTER_WEALTH_TABLE_IDENTITY.journalPages],
        rulebookPage: CHARACTER_WEALTH_TABLE_IDENTITY.rulebookPage,
      },
    },
    generatorVersion: CHARACTER_WEALTH_GENERATOR_VERSION,
    rows: extracted.rows,
  };
  return {
    ...artifactPayload,
    artifactDigest: digest(artifactCharacterWealthSha256(artifactPayload)),
  };
}

export function renderGeneratedCharacterWealthModule(policy) {
  return `// Generated by tools/starting-equipment/generate-character-wealth.mjs. Do not edit.\n\nimport type { CharacterWealthRow } from "./character-wealth-policy.js";\n\ntype GeneratedCharacterWealthPolicyArtifact = Readonly<{\n  schemaVersion: number;\n  policyId: "pf2e-remaster-character-wealth";\n  policyVersion: number;\n  dataDigest: string;\n  source: Readonly<{\n    pf2eVersion: string;\n    commit: string;\n    path: string;\n    journalId: string;\n    pageId: string;\n    fixtureDigest: string;\n    sourceDigest: string;\n    tableDigest: string;\n  }>;\n  tableIdentity: Readonly<{\n    heading: string;\n    classTokens: readonly string[];\n    headers: readonly string[];\n    attribution: Readonly<{\n      journalFooter: string;\n      book: string;\n      journalPages: readonly number[];\n      rulebookPage: number;\n    }>;\n  }>;\n  generatorVersion: number;\n  rows: readonly CharacterWealthRow[];\n  artifactDigest: string;\n}>;\n\nconst GENERATED_CHARACTER_WEALTH_POLICY_JSON = String.raw\`${JSON.stringify(policy, null, 2)}\`;\n\nexport const GENERATED_CHARACTER_WEALTH_POLICY = JSON.parse(\n  GENERATED_CHARACTER_WEALTH_POLICY_JSON\n) as GeneratedCharacterWealthPolicyArtifact;\n`;
}

export function parseGeneratedCharacterWealthModule(source) {
  if (typeof source !== "string") throw new Error("Generated Character Wealth source must be a string.");
  const match = /const GENERATED_CHARACTER_WEALTH_POLICY_JSON = String\.raw\s*`([\s\S]*?)`;/u.exec(source);
  if (!match) throw new Error("Generated Character Wealth source does not contain its canonical JSON payload.");
  const policy = JSON.parse(match[1]);
  assertGeneratedCharacterWealthIntegrity(policy);
  return policy;
}

export function assertGeneratedCharacterWealthIntegrity(policy) {
  assertRecord(policy, "Generated Character Wealth policy");
  assertExactKeys(
    policy,
    [
      "artifactDigest",
      "dataDigest",
      "generatorVersion",
      "policyId",
      "policyVersion",
      "rows",
      "schemaVersion",
      "source",
      "tableIdentity",
    ],
    "Generated Character Wealth policy",
  );
  if (policy.schemaVersion !== CHARACTER_WEALTH_SCHEMA_VERSION) {
    throw new Error("Generated Character Wealth policy has the wrong schema version.");
  }
  if (policy.policyId !== CHARACTER_WEALTH_POLICY_ID) {
    throw new Error("Generated Character Wealth policy has the wrong policy id.");
  }
  if (policy.policyVersion !== CHARACTER_WEALTH_POLICY_VERSION) {
    throw new Error("Generated Character Wealth policy has the wrong policy version.");
  }
  if (policy.generatorVersion !== CHARACTER_WEALTH_GENERATOR_VERSION) {
    throw new Error("Generated Character Wealth policy has the wrong generator version.");
  }

  assertGeneratedSource(policy.source);
  assertGeneratedTableIdentity(policy.tableIdentity);
  assertGeneratedRows(policy.rows);

  const dataDigest = digest(characterWealthDataSha256(policy.rows));
  if (policy.dataDigest !== dataDigest || policy.dataDigest !== PINNED_CHARACTER_WEALTH_DATA_DIGEST) {
    throw new Error("Generated Character Wealth data digest does not match the reviewed policy rows.");
  }
  if (policy.source.fixtureDigest !== PINNED_CHARACTER_WEALTH_FIXTURE_DIGEST) {
    throw new Error("Generated Character Wealth fixture digest does not match the reviewed generator input.");
  }
  const { artifactDigest, ...payload } = policy;
  if (artifactDigest !== digest(artifactCharacterWealthSha256(payload))) {
    throw new Error("Generated Character Wealth artifact digest does not match its payload.");
  }
}

export async function generateCharacterWealth({ fixturePath = DEFAULT_CHARACTER_WEALTH_FIXTURE_PATH } = {}) {
  const fixture = JSON.parse(await readFile(fixturePath, "utf8"));
  const policy = buildCharacterWealthPolicy(fixture);
  const source = renderGeneratedCharacterWealthModule(policy);
  return { policy, source };
}

export async function assertCharacterWealthRuntimeCurrent({ readRuntimeFile = readFile } = {}) {
  const configPath = path.join(repoRoot, "tsconfig.json");
  const config = ts.readConfigFile(configPath, ts.sys.readFile);
  if (config.error) throw new Error(formatTypeScriptDiagnostics([config.error]));
  const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, repoRoot, undefined, configPath);
  if (parsed.errors.length > 0) throw new Error(formatTypeScriptDiagnostics(parsed.errors));

  const program = ts.createProgram(parsed.fileNames, parsed.options);
  const emitted = new Map();
  const diagnostics = [];
  for (const sourcePath of CHARACTER_WEALTH_RUNTIME_SOURCE_PATHS) {
    const sourceFile = program.getSourceFile(sourcePath);
    if (!sourceFile) throw new Error(`TypeScript could not load ${path.relative(repoRoot, sourcePath)}.`);
    const result = program.emit(sourceFile, (fileName, data) => emitted.set(path.resolve(fileName), data));
    diagnostics.push(...result.diagnostics);
  }
  if (diagnostics.length > 0) throw new Error(formatTypeScriptDiagnostics(diagnostics));

  for (const [outputPath, expected] of emitted) {
    const actual = await readRuntimeFile(outputPath, "utf8").catch(() => "");
    if (normalizeLineEndings(actual) !== normalizeLineEndings(expected)) {
      throw new Error(
        `Compiled Character Wealth runtime is stale at ${path.relative(repoRoot, outputPath)}. Run npm run build and commit the result.`,
      );
    }
  }
}

export function materializeCharacterWealthNegativeFixture(baseFixture, descriptor) {
  assertRecord(baseFixture, "Character Wealth base fixture");
  assertRecord(descriptor, "Character Wealth negative fixture");
  if (
    descriptor.schemaVersion !== 1 ||
    descriptor.fixtureKind !== "synthetic-character-wealth-negative" ||
    descriptor.baseFixture !== path.basename(DEFAULT_CHARACTER_WEALTH_FIXTURE_PATH)
  ) {
    throw new Error("Character Wealth negative fixture descriptor is invalid.");
  }
  assertRecord(descriptor.mutation, "Character Wealth negative fixture mutation");
  assertExactKeys(descriptor.mutation, ["id"], "Character Wealth negative fixture mutation");
  const materialized = structuredClone(baseFixture);
  if (descriptor.mutation.id === "party-treasure-heading") {
    materialized.tableIdentity.heading = "Party Treasure by Level";
  } else if (descriptor.mutation.id === "premaster-table-class") {
    materialized.tableIdentity.classTokens = materialized.tableIdentity.classTokens.filter(
      (token) => token !== "remaster",
    );
  } else {
    throw new Error("Character Wealth negative fixture mutation is invalid.");
  }
  return materialized;
}

export function renderCharacterWealthFixtureJournal(fixture) {
  assertRecord(fixture, "Character Wealth fixture");
  assertRecord(fixture.tableIdentity, "Character Wealth fixture table identity");
  const identity = fixture.tableIdentity;
  const headers = identity.headers.map((header) => `<th>${escapeHtml(header)}</th>`).join("");
  const rows = fixture.rows
    .map(
      (row) =>
        `<tr><td>${row.characterLevel}</td><td>${renderAllowances(row.permanentItemAllowances)}</td><td>${row.permanentRecipeCurrencyCopper} cp</td><td>${row.lumpSumCopper} cp</td></tr>`,
    )
    .join("");
  const content = `<h2>${escapeHtml(identity.heading)}</h2><table class="${identity.classTokens.map(escapeHtml).join(" ")}"><thead><tr>${headers}</tr></thead><tbody>${rows}</tbody></table><p>${escapeHtml(identity.attribution.journalFooter)}</p>`;
  return {
    _id: fixture.source.journalId,
    pages: [{ _id: fixture.source.pageId, text: { content } }],
  };
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  if (options.help) {
    console.log(usage());
    return;
  }
  if (options.captureFrom) await captureFixtures(options.captureFrom);

  const { source } = await generateCharacterWealth({ fixturePath: options.fixturePath });
  if (options.check) {
    const existing = await readFile(options.outputPath, "utf8").catch(() => "");
    if (normalizeLineEndings(existing) !== normalizeLineEndings(source)) {
      throw new Error(
        "Generated Character Wealth policy is stale. Run npm run generate:character-wealth and commit the result.",
      );
    }
    await assertCharacterWealthRuntimeCurrent();
    console.log("Character Wealth generated policy is current.");
    return;
  }

  await mkdir(path.dirname(options.outputPath), { recursive: true });
  await writeFile(options.outputPath, source, "utf8");
  console.log(`Generated ${path.relative(repoRoot, options.outputPath)}.`);
}

function parseArgs(argv) {
  const options = {
    captureFrom: "",
    check: false,
    fixturePath: DEFAULT_CHARACTER_WEALTH_FIXTURE_PATH,
    help: false,
    outputPath: DEFAULT_CHARACTER_WEALTH_OUTPUT_PATH,
  };
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--check") options.check = true;
    else if (arg === "--help") options.help = true;
    else if (["--capture-from", "--fixture", "--out"].includes(arg)) {
      const value = argv[index + 1];
      if (!value || value.startsWith("--")) throw new Error(`Missing value for ${arg}.`);
      if (arg === "--capture-from") options.captureFrom = path.resolve(value);
      if (arg === "--fixture") options.fixturePath = path.resolve(value);
      if (arg === "--out") options.outputPath = path.resolve(value);
      index += 1;
    } else throw new Error(`Unknown argument: ${arg}`);
  }
  return options;
}

function usage() {
  return `Usage: node tools/starting-equipment/generate-character-wealth.mjs [options]\n\nOptions:\n  --check                 Fail if the checked-in generated module is stale.\n  --fixture <path>        Read a different pinned fixture.\n  --out <path>            Write a different generated TypeScript module.\n  --capture-from <repo>   Refresh fixtures from the pinned commit in a local PF2E checkout.\n  --help                  Show this help.\n`;
}

async function captureFixtures(pf2eRepo) {
  const pinnedJournal = readJournalAtCommit(
    pf2eRepo,
    PINNED_CHARACTER_WEALTH_SOURCE.pf2eCommit,
    PINNED_CHARACTER_WEALTH_SOURCE.upstreamPath,
  );
  if (pinnedJournal._id !== PINNED_CHARACTER_WEALTH_SOURCE.journalId) {
    throw new Error("Pinned PF2E GM Screen journal id changed unexpectedly.");
  }
  const pinnedPages = pinnedJournal.pages.filter((page) => page?._id === PINNED_CHARACTER_WEALTH_SOURCE.pageId);
  if (pinnedPages.length !== 1) throw new Error("Pinned PF2E Character Wealth page could not be resolved exactly.");

  const pageContent = pinnedPages[0]?.text?.content;
  if (typeof pageContent !== "string" || pageContent.length === 0) {
    throw new Error("Pinned PF2E Character Wealth page has no HTML content.");
  }
  if (digest(sha256(pageContent)) !== PINNED_CHARACTER_WEALTH_SOURCE.sourceDigest) {
    throw new Error("Pinned PF2E source digest does not match the reviewed journal page.");
  }
  const extracted = extractCharacterWealthJournal({
    _id: pinnedJournal._id,
    pages: [pinnedPages[0]],
  });
  if (digest(extracted.tableContentSha256) !== PINNED_CHARACTER_WEALTH_SOURCE.tableDigest) {
    throw new Error("Pinned PF2E table digest does not match the reviewed Character Wealth table.");
  }

  const pinnedFixture = buildPinnedFixture(extracted.rows);
  extractPinnedCharacterWealthFixture(pinnedFixture);
  const partyFixture = buildNegativeDescriptor("party-treasure-heading");
  const premasterFixture = buildNegativeDescriptor("premaster-table-class");

  await mkdir(path.dirname(DEFAULT_CHARACTER_WEALTH_FIXTURE_PATH), { recursive: true });
  await Promise.all([
    writeJson(DEFAULT_CHARACTER_WEALTH_FIXTURE_PATH, pinnedFixture),
    writeJson(PARTY_TREASURE_NEGATIVE_FIXTURE_PATH, partyFixture),
    writeJson(PREMASTER_NEGATIVE_FIXTURE_PATH, premasterFixture),
  ]);
  console.log("Captured the normalized pinned Character Wealth policy and synthetic negative fixtures.");
}

function buildPinnedFixture(rows) {
  return {
    schemaVersion: 1,
    fixtureKind: "pinned-pf2e-character-wealth-policy",
    source: { ...PINNED_CHARACTER_WEALTH_SOURCE },
    tableIdentity: {
      heading: CHARACTER_WEALTH_TABLE_IDENTITY.heading,
      classTokens: [...CHARACTER_WEALTH_TABLE_IDENTITY.classTokens],
      headers: [...CHARACTER_WEALTH_TABLE_IDENTITY.headers],
      attribution: {
        journalFooter: CHARACTER_WEALTH_TABLE_IDENTITY.attribution,
        book: CHARACTER_WEALTH_TABLE_IDENTITY.book,
        journalPages: [...CHARACTER_WEALTH_TABLE_IDENTITY.journalPages],
        rulebookPage: CHARACTER_WEALTH_TABLE_IDENTITY.rulebookPage,
      },
    },
    rows,
  };
}

function buildNegativeDescriptor(id) {
  return {
    schemaVersion: 1,
    fixtureKind: "synthetic-character-wealth-negative",
    baseFixture: path.basename(DEFAULT_CHARACTER_WEALTH_FIXTURE_PATH),
    mutation: { id },
  };
}

function readJournalAtCommit(repoPath, commit, upstreamPath) {
  const content = execFileSync("git", ["show", `${commit}:${upstreamPath}`], {
    cwd: repoPath,
    encoding: "utf8",
    maxBuffer: 16 * 1024 * 1024,
    stdio: ["ignore", "pipe", "pipe"],
  });
  return JSON.parse(content);
}

function assertGeneratedSource(source) {
  assertRecord(source, "Generated Character Wealth source");
  assertExactKeys(
    source,
    ["commit", "fixtureDigest", "journalId", "pageId", "path", "pf2eVersion", "sourceDigest", "tableDigest"],
    "Generated Character Wealth source",
  );
  const expected = {
    pf2eVersion: PINNED_CHARACTER_WEALTH_SOURCE.pf2eVersion,
    commit: PINNED_CHARACTER_WEALTH_SOURCE.pf2eCommit,
    path: PINNED_CHARACTER_WEALTH_SOURCE.upstreamPath,
    journalId: PINNED_CHARACTER_WEALTH_SOURCE.journalId,
    pageId: PINNED_CHARACTER_WEALTH_SOURCE.pageId,
    sourceDigest: PINNED_CHARACTER_WEALTH_SOURCE.sourceDigest,
    tableDigest: PINNED_CHARACTER_WEALTH_SOURCE.tableDigest,
  };
  for (const [key, value] of Object.entries(expected)) {
    if (source[key] !== value) throw new Error(`Generated Character Wealth source ${key} is invalid.`);
  }
  assertDigest(source.fixtureDigest, "fixture digest");
}

function assertGeneratedTableIdentity(identity) {
  assertRecord(identity, "Generated Character Wealth table identity");
  assertExactKeys(identity, ["attribution", "classTokens", "headers", "heading"], "table identity");
  const expected = {
    heading: CHARACTER_WEALTH_TABLE_IDENTITY.heading,
    classTokens: CHARACTER_WEALTH_TABLE_IDENTITY.classTokens,
    headers: CHARACTER_WEALTH_TABLE_IDENTITY.headers,
  };
  for (const [key, value] of Object.entries(expected)) {
    if (canonicalJson(identity[key]) !== canonicalJson(value)) {
      throw new Error(`Generated Character Wealth table identity ${key} is invalid.`);
    }
  }
  assertRecord(identity.attribution, "Generated Character Wealth attribution");
  assertExactKeys(
    identity.attribution,
    ["book", "journalFooter", "journalPages", "rulebookPage"],
    "table attribution",
  );
  const expectedAttribution = {
    journalFooter: CHARACTER_WEALTH_TABLE_IDENTITY.attribution,
    book: CHARACTER_WEALTH_TABLE_IDENTITY.book,
    journalPages: CHARACTER_WEALTH_TABLE_IDENTITY.journalPages,
    rulebookPage: CHARACTER_WEALTH_TABLE_IDENTITY.rulebookPage,
  };
  if (canonicalJson(identity.attribution) !== canonicalJson(expectedAttribution)) {
    throw new Error("Generated Character Wealth table attribution is invalid.");
  }
}

function assertGeneratedRows(rows) {
  if (!Array.isArray(rows) || rows.length !== 20) {
    throw new Error("Generated Character Wealth policy must contain 20 rows.");
  }
  for (let index = 0; index < rows.length; index += 1) {
    const row = rows[index];
    assertRecord(row, `Generated Character Wealth row ${index + 1}`);
    assertExactKeys(
      row,
      ["characterLevel", "lumpSumCopper", "permanentItemAllowances", "permanentRecipeCurrencyCopper"],
      `Generated Character Wealth row ${index + 1}`,
    );
    if (row.characterLevel !== index + 1) {
      throw new Error("Generated Character Wealth rows must be uniquely ordered from level 1 through 20.");
    }
    for (const key of ["permanentRecipeCurrencyCopper", "lumpSumCopper"]) {
      if (!Number.isSafeInteger(row[key]) || row[key] < 0) {
        throw new Error(`Generated Character Wealth ${key} must be a nonnegative safe integer.`);
      }
    }
    if (!Array.isArray(row.permanentItemAllowances)) {
      throw new Error("Generated Character Wealth permanent-item allowances must be an array.");
    }
    let previousLevel = Number.POSITIVE_INFINITY;
    const seen = new Set();
    for (const allowance of row.permanentItemAllowances) {
      assertRecord(allowance, "Generated Character Wealth allowance");
      assertExactKeys(allowance, ["count", "itemLevel"], "Generated Character Wealth allowance");
      if (
        !Number.isSafeInteger(allowance.itemLevel) ||
        !Number.isSafeInteger(allowance.count) ||
        allowance.itemLevel < 1 ||
        allowance.itemLevel >= row.characterLevel ||
        allowance.count < 1 ||
        allowance.itemLevel >= previousLevel ||
        seen.has(allowance.itemLevel)
      ) {
        throw new Error("Generated Character Wealth allowances are invalid or out of order.");
      }
      previousLevel = allowance.itemLevel;
      seen.add(allowance.itemLevel);
    }
  }
}

function assertDigest(value, label) {
  if (typeof value !== "string" || !/^sha256:[0-9a-f]{64}$/u.test(value)) {
    throw new Error(`Generated Character Wealth ${label} is invalid.`);
  }
}

function assertRecord(value, label) {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    throw new Error(`${label} must be an object.`);
  }
}

function assertExactKeys(value, expectedKeys, label) {
  const actual = Object.keys(value).sort();
  const expected = [...expectedKeys].sort();
  if (canonicalJson(actual) !== canonicalJson(expected)) {
    throw new Error(`${label} must contain exactly ${expected.join(", ")}.`);
  }
}

function renderAllowances(allowances) {
  if (!Array.isArray(allowances) || allowances.length === 0) return "-";
  return allowances
    .map((allowance) => `<strong>${allowance.itemLevel}${ordinalSuffix(allowance.itemLevel)}</strong>: ${allowance.count}`)
    .join(", ");
}

function ordinalSuffix(value) {
  const lastTwo = value % 100;
  if (lastTwo >= 11 && lastTwo <= 13) return "th";
  if (value % 10 === 1) return "st";
  if (value % 10 === 2) return "nd";
  if (value % 10 === 3) return "rd";
  return "th";
}

function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

function normalizeLineEndings(value) {
  return value.replace(/\r\n?/gu, "\n");
}

function formatTypeScriptDiagnostics(diagnostics) {
  return ts.formatDiagnosticsWithColorAndContext(diagnostics, {
    getCanonicalFileName: (fileName) => fileName,
    getCurrentDirectory: () => repoRoot,
    getNewLine: () => "\n",
  });
}

async function writeJson(filePath, value) {
  await writeFile(filePath, `${JSON.stringify(value, null, 2)}\n`, "utf8");
}

const invokedPath = process.argv[1] ? path.resolve(process.argv[1]) : "";
if (invokedPath === fileURLToPath(import.meta.url)) {
  await main().catch((error) => {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  });
}
